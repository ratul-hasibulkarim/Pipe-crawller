"""bot_params.yaml -> firmware/include/bot_params.h (and pi/app/bot_params.json).

Every constant the firmware uses comes from here; derived values (ratios, LUTs, thresholds)
are computed with the same code as the design calcs (calc/mechanism.py).

    python3 tools/gen_params.py [--check]
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "calc"))
import design_calcs as dc  # noqa: E402
import mechanism as mech  # noqa: E402

OUT_H = ROOT / "firmware" / "include" / "bot_params.h"
OUT_JSON = ROOT / "pi" / "app" / "bot_params.json"
HEADER = "AUTO-GENERATED by tools/gen_params.py from params/bot_params.yaml - do not edit."


def size_constants(p: dict, size: str) -> dict[str, float | int]:
    """Flat constant table for one size."""
    c, s = p["common"], p["sizes"][size]
    lim, ctl, pw = c["motor_limits"], c["control"], c["power"]
    geo = mech.arm_geometry(p, size)
    th0 = mech.theta_for_pipe(geo, s["pipe_id_min_mm"])
    th1 = mech.theta_for_pipe(geo, s["pipe_id_max_mm"])
    drv = p["motors"][s["drive"]["motor"]]
    exp_m = p["motors"][s["expansion"]["motor"]]
    usteps = lim["steps_per_rev"] * lim["microsteps"]
    ratio = dc.expansion_ratio(s)
    n_tot = dc.required_total_normal_force(s["mass_target_kg"], 90, c["wheel_wet_friction_coeff"], c["grip_safety_factor"], c["gravity_m_s2"])
    grip_work = n_tot / c["arm_count"]
    k = s["rocker"]["spring_rate_n_mm"]
    sweep_rad_s = (th1 - th0) / c["sweep_time_s"]
    rail = s["power"]["motor_rail_v"]
    rpm_lim = (exp_m["max_rpm_24v"] if rail >= 24 else exp_m["max_rpm"]) * lim["rpm_utilization"]
    series = s["power"]["battery_series"]
    out: dict[str, float | int] = {
        "ARM_COUNT": c["arm_count"],
        "ARM_ANGLE_DEG": c["arm_angle_deg"],
        "PIPE_ID_MIN_MM": s["pipe_id_min_mm"],
        "PIPE_ID_MAX_MM": s["pipe_id_max_mm"],
        "WHEEL_DIA_MM": s["wheel_dia_mm"],
        "WHEELBASE_MM": s["wheelbase_mm"],
        "MASS_KG": s["mass_target_kg"],
        "PIVOT_R_MM": geo.pivot_r,
        "LEVER_LEN_MM": geo.lever_len,
        "ROCKER_OFFSET_MM": geo.rocker_offset,
        "THETA_MIN_RAD": th0,
        "THETA_MAX_RAD": th1,
        "MOTOR_USTEPS_PER_REV": usteps,
        "EXPANSION_RATIO": ratio,
        "EXPANSION_USTEPS_PER_RAD": usteps * ratio / (2 * math.pi),
        "EXPANSION_MAX_RAD_S": min(sweep_rad_s * 1.25, rpm_lim / 60 * 2 * math.pi / ratio),
        "EXPANSION_ACCEL_RAD_S2": sweep_rad_s * 4,
        "EXPANSION_CURRENT_A": exp_m["rated_current_a"] * pw["motor_run_current_fraction"],
        "DRIVE_WORM_RATIO": s["drive"]["worm_ratio"],
        "DRIVE_USTEPS_PER_MM": usteps * s["drive"]["worm_ratio"] / (math.pi * s["wheel_dia_mm"]),
        "DRIVE_CURRENT_A": drv["rated_current_a"] * pw["motor_run_current_fraction"],
        "HOLD_CURRENT_FRAC": pw["motor_hold_current_fraction"],
        "MAX_SPEED_MM_S": s["max_speed_mm_s"],
        "MAX_ACCEL_MM_S2": s["max_speed_mm_s"] * 2.0,
        "MAX_GRIP_N": s["max_grip_force_per_arm_n"],
        "WORKING_GRIP_N": round(grip_work, 2),
        "SPRING_RATE_N_MM": k,
        # spring sits at mid-travel at the working grip: preload = working - k * travel
        "SPRING_PRELOAD_N": round(grip_work - k * c["arm_compliance_travel_mm"], 2),
        "COMPLIANCE_TRAVEL_MM": c["arm_compliance_travel_mm"],
        "CONTACT_SLIDE_MM": 0.3,
        "GRIP_LOW_N": round(0.6 * grip_work, 2),
        "REGRIP_DEADBAND_N": round(max(1.0, 0.08 * grip_work), 2),
        "MU_WET": c["wheel_wet_friction_coeff"],
        "MU_DRY": c["wheel_dry_friction_coeff"],
        "BATTERY_SERIES": series,
        "BATTERY_CRITICAL_V": series * ctl["critical_v_per_cell"],
        "BATTERY_LOW_V": series * (ctl["critical_v_per_cell"] + 0.2),
        "BATTERY_FULL_V": series * 4.2,
        "SUPPLY_MIN_V": pw["tether_min_v_at_robot"],
        "TETHER_V": pw["tether_v"],
        "MOTOR_RAIL_V": rail,
        "DRIVE_LOOP_HZ": ctl["drive_loop_hz"],
        "EXPANSION_LOOP_HZ": ctl["expansion_loop_hz"],
        "TELEMETRY_HZ": ctl["telemetry_hz"],
        "WATCHDOG_TIMEOUT_MS": ctl["watchdog_timeout_ms"],
        "SLIP_DETECT_MS": ctl["slip_detect_ms"],
        "SLIP_VEL_ERR_FRAC": ctl["slip_velocity_error_frac"],
        "DRIVE_TTL_MS": ctl["drive_ttl_ms"],
        "EXPAND_TTL_MS": ctl["expand_ttl_ms"],
        "DRIVE_OVER_CURRENT_A": ctl["drive_over_current_frac"] * s["power"]["buck_motor_a"],
        "EXP_OVER_CURRENT_A": ctl["expand_over_current_frac"] * s["power"]["buck_motor_a"],
        "THERMAL_DERATE_C": ctl["thermal_derate_c"],
        "THERMAL_TRIP_C": ctl["thermal_trip_c"],
        "GIMBAL_TILT_MIN_DEG": c["gimbal_tilt_range_deg"][0],
        "GIMBAL_TILT_MAX_DEG": c["gimbal_tilt_range_deg"][1],
        "BEND_RADIUS_MM": c["bend_radius_over_pipe_id"] * s["pipe_id_min_mm"],
        # --- plant constants used by the software-in-the-loop simulator (sim/) ---
        "GRAVITY": c["gravity_m_s2"],
        "BODY_DIA_MM": s["body_dia_mm"],
        "BODY_LENGTH_MM": sum(s["layout"][k] for k in ("rear_pod_mm", "mid_zone_mm", "joint_mm", "front_pod_mm")),
        "DRIVE_HOLDING_NM": drv["holding_torque_nm"],
        "DRIVE_MAX_RPM": drv["max_rpm_24v"] if rail >= 24 else drv["max_rpm"],
        "DRIVE_WORM_EFF": dc.thread_metrics(c["drive_worm"]["lead_angle_deg"], c["drive_worm"]["friction_coeff"], 0.0).efficiency,
        "DRIVE_RATED_A": drv["rated_current_a"],
        "DRIVE_WINDING_OHM": drv["winding_ohm"],
        "EXP_HOLDING_NM": exp_m["holding_torque_nm"],
        "EXP_RATED_A": exp_m["rated_current_a"],
        "EXP_WINDING_OHM": exp_m["winding_ohm"],
        "EXP_CHAIN_EFF": dc.expansion_worm(p, size).efficiency * c["expansion_worm"]["bevel_efficiency"] * c["expansion_worm"]["planetary_efficiency"],
        "SQUEEZE_TORQUE_FRAC": lim["squeeze_torque_fraction"],
        "ELECTRONICS_W": s["power"]["compute_avg_w"] + pw["camera_w"] + pw["mcu_sensors_w"],
        "LED_WHITE_W": pw["led_white_w_max"],
        "LED_IR_W": pw["led_ir_w_max"],
        "BATTERY_PARALLEL": s["power"]["battery_parallel"],
        "CELL_AH": s["power"]["cell_ah"],
        "TETHER_LOOP_OHM_PER_M": pw["tether_conductor_ohm_per_m"],
        "CONVERTER_EFF": pw["converter_efficiency"],
        "TETHER_MAX_M": max(c["tether_length_m"]),
    }
    return out


def lut(p: dict, size: str, n: int = 33) -> list[tuple[float, float]]:
    """(pipe ID mm, theta rad) table."""
    geo = mech.arm_geometry(p, size)
    th0 = mech.theta_for_pipe(geo, p["sizes"][size]["pipe_id_min_mm"])
    th1 = mech.theta_for_pipe(geo, p["sizes"][size]["pipe_id_max_mm"])
    return [(mech.pipe_for_theta(geo, th), th) for th in mech.theta_samples(th0, th1, n)]


INT_KEYS = {"BATTERY_PARALLEL", "ARM_COUNT", "ARM_ANGLE_DEG", "MOTOR_USTEPS_PER_REV", "BATTERY_SERIES", "DRIVE_LOOP_HZ", "EXPANSION_LOOP_HZ",
            "TELEMETRY_HZ", "WATCHDOG_TIMEOUT_MS", "SLIP_DETECT_MS", "DRIVE_TTL_MS", "EXPAND_TTL_MS", "DRIVE_WORM_RATIO"}


def fmt(v: float | int) -> str:
    """C++ float literal (always with a decimal point)."""
    s = f"{float(v):.7g}"
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def gen_header(p: dict) -> str:
    """bot_params.h text."""
    o = [f"// {HEADER}", "#pragma once", "#include <cstdint>", "", "// Select the build size with -DPIPEBOT_SIZE_S / _M / _L (default M).",
         "#if !defined(PIPEBOT_SIZE_S) && !defined(PIPEBOT_SIZE_M) && !defined(PIPEBOT_SIZE_L)", "#define PIPEBOT_SIZE_M", "#endif", "",
         "namespace params {"]
    for size in p["sizes"]:
        o.append(f"namespace size_{size} {{")
        o.append(f'constexpr char NAME = \'{size}\';')
        for k, v in size_constants(p, size).items():
            if k in INT_KEYS:
                o.append(f"constexpr int32_t {k} = {int(v)};")
            else:
                o.append(f"constexpr float {k} = {fmt(v)};")
        table = lut(p, size)
        o.append(f"constexpr int DIAMETER_LUT_N = {len(table)};")
        o.append("constexpr float DIAMETER_LUT_MM[DIAMETER_LUT_N] = {" + ", ".join(f"{d:.3f}f" for d, _ in table) + "};")
        o.append("constexpr float DIAMETER_LUT_THETA[DIAMETER_LUT_N] = {" + ", ".join(f"{t:.6f}f" for _, t in table) + "};")
        o.append(f"}}  // namespace size_{size}")
        o.append("")
    o += ["#if defined(PIPEBOT_SIZE_S)", "using namespace size_S;", "#elif defined(PIPEBOT_SIZE_L)", "using namespace size_L;", "#else",
          "using namespace size_M;", "#endif", "}  // namespace params", ""]
    return "\n".join(o)


def main() -> int:
    """Generate or check."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    p = yaml.safe_load((ROOT / "params" / "bot_params.yaml").read_text())
    outputs = {OUT_H: gen_header(p),
               OUT_JSON: json.dumps({s: size_constants(p, s) | {"lut": lut(p, s)} for s in p["sizes"]}, indent=1) + "\n"}
    stale = []
    for path, text in outputs.items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale:", *stale)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
